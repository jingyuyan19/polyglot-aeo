/**
 * Build-time generator: OpenCC dictionary → compact glyph maps for runtime
 * locale-script validation. Run via `pnpm run generate:locale-maps`.
 */
import { mkdirSync, readFileSync, writeFileSync } from "fs"
import { dirname, join } from "path"
import { fileURLToPath } from "url"

import OpenCC from "opencc-js"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, "..")
const DICT_DIR = join(ROOT, "node_modules/opencc-js/dist/esm-lib/dict")
const OUT_DIR = join(ROOT, "src/lib/locale-script/data")
const PROMPT_SAMPLES = join(ROOT, "src/lib/locale-script/prompt-samples.ts")

const MAX_PHRASE_LEN = 12
const MAX_JA_PHRASES = 4000

type GlyphMap = Record<string, string>
type PhraseEntry = { found: string; expected: string; kind: "simplified" | "traditional" }

function readDictExport(name: string): string {
  const raw = readFileSync(join(DICT_DIR, `${name}.js`), "utf8")
  const m = raw.match(/export default "([\s\S]*)";/)
  if (!m) throw new Error(`Could not parse dict ${name}`)
  return m[1]
}

function parsePairs(dict: string): Array<[string, string]> {
  const pairs: Array<[string, string]> = []
  for (const entry of dict.split("|")) {
    const parts = entry.trim().split(/\s+/)
    if (parts.length >= 2) {
      pairs.push([parts[0], parts[1]])
    }
  }
  return pairs
}

function singleCharPairs(pairs: Array<[string, string]>): Array<[string, string]> {
  return pairs.filter(([a, b]) => [...a].length === 1 && [...b].length === 1 && a !== b)
}

function mergeGlyphMap(target: GlyphMap, pairs: Array<[string, string]>): void {
  for (const [wrong, expected] of pairs) {
    if (target[wrong] && target[wrong] !== expected) continue
    target[wrong] = expected
  }
}

function buildJaPhrases(
  cn2jp: (s: string) => string,
  extraPairs: Array<[string, string]>,
): PhraseEntry[] {
  const seen = new Set<string>()
  const out: PhraseEntry[] = []

  const add = (found: string, expected: string, kind: PhraseEntry["kind"]) => {
    if (found.length < 2 || found.length > MAX_PHRASE_LEN) return
    if (found === expected || seen.has(found)) return
    seen.add(found)
    out.push({ found, expected, kind })
  }

  for (const entry of parsePairs(readDictExport("STPhrases"))) {
    const [found] = entry
    const expected = cn2jp(found)
    if (expected !== found) add(found, expected, "simplified")
    if (out.length >= MAX_JA_PHRASES) break
  }

  for (const [found, expected] of extraPairs) {
    add(found, expected, "traditional")
    if (out.length >= MAX_JA_PHRASES) break
  }

  for (const entry of parsePairs(readDictExport("JPShinjitaiPhrases"))) {
    const [jp, trad] = entry
    if (jp !== trad) add(trad, jp, "traditional")
    if (out.length >= MAX_JA_PHRASES) break
  }

  out.sort((a, b) => b.found.length - a.found.length)
  return out.slice(0, MAX_JA_PHRASES)
}

function writePromptSamples(cnToJp: GlyphMap): void {
  const preferred = ["网", "选", "决", "经", "诀", "听", "观", "语", "说", "读"]
  const samples: Array<{ wrong: string; expected: string }> = []
  const seen = new Set<string>()
  for (const wrong of preferred) {
    const expected = cnToJp[wrong]
    if (!expected) continue
    samples.push({ wrong, expected })
    seen.add(wrong)
  }
  for (const [wrong, expected] of Object.entries(cnToJp)) {
    if (samples.length >= 12) break
    if (seen.has(wrong)) continue
    samples.push({ wrong, expected })
  }

  const body = `/**
 * AUTO-GENERATED by scripts/generate-locale-glyph-maps.ts — do not edit.
 * Sample glyph pairs for AI prompt script-integrity rules (ja).
 */
export const JA_GLYPH_PROMPT_SAMPLES = ${JSON.stringify(samples, null, 2)} as const
`
  writeFileSync(PROMPT_SAMPLES, body, "utf8")
}

function main(): void {
  mkdirSync(OUT_DIR, { recursive: true })

  const cn2jp = OpenCC.Converter({ from: "cn", to: "jp" })

  const stChars = singleCharPairs(parsePairs(readDictExport("STCharacters")))
  const tsChars = singleCharPairs(parsePairs(readDictExport("TSCharacters")))
  const jpVariants = singleCharPairs(parsePairs(readDictExport("JPVariants")))
  const jpShinjitai = singleCharPairs(parsePairs(readDictExport("JPShinjitaiCharacters")))

  const cnToJp: GlyphMap = {}
  for (const [simp] of stChars) {
    const expected = cn2jp(simp)
    if ([...expected].length === 1 && expected !== simp) {
      cnToJp[simp] = expected
    }
  }

  const twToJp: GlyphMap = {}
  mergeGlyphMap(twToJp, jpVariants)
  for (const [jp, trad] of jpShinjitai) {
    twToJp[trad] = jp
  }

  const cnToTw: GlyphMap = {}
  for (const [simp, trad] of stChars) {
    cnToTw[simp] = trad
  }

  const twToCn: GlyphMap = {}
  for (const [trad, simp] of tsChars) {
    twToCn[trad] = simp
  }

  const jaPhrases = buildJaPhrases(cn2jp, parsePairs(readDictExport("JPShinjitaiPhrases")))

  const pkg = JSON.parse(
    readFileSync(join(ROOT, "node_modules/opencc-js/package.json"), "utf8"),
  ) as { version: string }

  const metadata = {
    openccVersion: pkg.version,
    entryCounts: {
      cnToJp: Object.keys(cnToJp).length,
      twToJp: Object.keys(twToJp).length,
      cnToTw: Object.keys(cnToTw).length,
      twToCn: Object.keys(twToCn).length,
      jaPhrases: jaPhrases.length,
    },
  }

  writeFileSync(join(OUT_DIR, "cn-to-jp.json"), JSON.stringify(cnToJp))
  writeFileSync(join(OUT_DIR, "tw-to-jp.json"), JSON.stringify(twToJp))
  writeFileSync(join(OUT_DIR, "cn-to-tw.json"), JSON.stringify(cnToTw))
  writeFileSync(join(OUT_DIR, "tw-to-cn.json"), JSON.stringify(twToCn))
  writeFileSync(join(OUT_DIR, "ja-phrases.json"), JSON.stringify(jaPhrases))
  writeFileSync(join(OUT_DIR, "metadata.json"), JSON.stringify(metadata, null, 2))

  writePromptSamples(cnToJp)

  console.log("Generated locale glyph maps:", metadata.entryCounts)
}

main()
